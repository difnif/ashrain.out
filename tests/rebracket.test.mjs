// node tests/rebracket.test.mjs — 괄호 규칙(mathir.rebracket / renderHtml) 검사
import assert from "node:assert/strict";
import { rebracket, renderHtml } from "../src/lib/mathir.js";

let n = 0, failed = 0;
function test(name, fn) {
  n++;
  try { fn(); console.log("ok   -", name); }
  catch (e) { failed++; console.log("FAIL -", name); console.log("      " + String(e?.message || e).split("\n").join("\n      ")); }
}
const eq = (a, b) => assert.equal(rebracket(a), b);

test("묶음 괄호 한 겹은 그대로", () => {
  eq("(x − 3)(x − 5) = 0", "(x − 3)(x − 5) = 0");
  eq("2(x + 1) − 3(x − 2)", "2(x + 1) − 3(x − 2)");
  eq("(-5) × (-3) = 15", "(-5) × (-3) = 15");
  eq("괄호 없음", "괄호 없음");
});

test("두 겹은 바깥이 중괄호, 세 겹은 대괄호", () => {
  eq("(x − (-4))(x − (-3)) = 0", "{x − (-4)}{x − (-3)} = 0");
  eq("((-9) + 13) ÷ 2 = 2", "{(-9) + 13} ÷ 2 = 2");
  eq("(-10 + (-2)) ÷ 2", "{-10 + (-2)} ÷ 2");
  eq("y − (-1) = 2(x − (-6))", "y − (-1) = 2{x − (-6)}");
  eq("(③ × (-4)) − (④ × 2)", "{③ × (-4)} − (④ × 2)");
  eq("(3² + 1² + (-2)² + (-3)²) ÷ 4", "{3² + 1² + (-2)² + (-3)²} ÷ 4");
  eq("((1 + i)/(1 − i))^15", "{(1 + i)/(1 − i)}^15");
  eq("(((-2) + 3) × 4 − 1) ÷ 2", "[{(-2) + 3} × 4 − 1] ÷ 2");
  eq("(-31 − (-7))/(7 − 1)", "{-31 − (-7)}/(7 − 1)");
});

test("연산자 뒤 양수만 든 괄호는 벗기고, 벗긴 괄호는 겹으로 세지 않는다", () => {
  eq("(x − (3))(x − (5)) = 0", "(x − 3)(x − 5) = 0");
  eq("2(x − (-6))(x − (4)) = 0", "2{x − (-6)}(x − 4) = 0");
  eq("x² − 2 × (4)x + 16", "x² − 2 × 4x + 16");
  eq("-1 × (5) + (2) × (-4)", "-1 × 5 + 2 × (-4)");
  eq("(x − (4))² = 0", "(x − 4)² = 0");
  eq("(1) 첫째 조건", "(1) 첫째 조건");           // 번호 매김은 연산자 뒤가 아니다
  eq("f(2) = 5", "f(2) = 5");                    // 함수값
});

test("함수·기호 표기는 소괄호로 두고, 그 안의 묶음만 새로 센다", () => {
  eq("f(f(2)) = 9", "f(f(2)) = 9");
  eq("n((A ∪ B)ᶜ) = n(U) − n(A ∪ B)", "n((A ∪ B)ᶜ) = n(U) − n(A ∪ B)");
  eq("P((A ∪ B)ᶜ) = 1 − P(A ∪ B)", "P((A ∪ B)ᶜ) = 1 − P(A ∪ B)");
  eq("√((16 − 1)² + (7 − (-1))²) = 17", "√((16 − 1)² + {7 − (-1)}²) = 17");
  eq("2sin²(x/2)", "2sin²(x/2)");
  eq("f′(x₀) (f(x₀) = y₀)", "f′(x₀) (f(x₀) = y₀)");
  eq("f((x − (-1))²)", "f({x − (-1)}²)");
  eq("(E(X))² 과 (f(x))²", "{E(X)}² 과 {f(x)}²");
  eq("log₂(x + 1)", "log₂(x + 1)");
  eq("(f(q) − f(p))/(q − p)", "{f(q) − f(p)}/(q − p)");
  eq("Sₙ = n(2a + (n − 1)d)/2", "Sₙ = n{2a + (n − 1)d}/2");      // 한 글자 소문자는 계수
  eq("x(x − (-1)) = 0", "x{x − (-1)} = 0");
  eq("n! ÷ (r!(n − r)!)", "n! ÷ {r!(n − r)!}");
  eq("(5^(1/3))⁶ = 25", "(5^(1/3))⁶ = 25");                       // 지수 표기 괄호는 겹으로 안 센다
  eq("B(n, p), N(m, σ²)", "B(n, p), N(m, σ²)");
});

test("여는 괄호 바로 안의 양수 괄호도 벗긴다", () => {
  eq("b = −((0) + (1)) = -1", "b = −(0 + 1) = -1");
  eq("b = −((-3) + (15)) = -12", "b = −{(-3) + 15} = -12");
});

test("순서쌍·좌표·구간과 문장 속 괄호는 그대로", () => {
  eq("(4 + (-3), -2) = (1, -2)", "(4 + (-3), -2) = (1, -2)");
  eq("(21, -2 × (-1) − 1) = (21, 1)", "(21, -2 × (-1) − 1) = (21, 1)");
  eq("(-5 + (2), -3 + (5)) = (-3, 2)", "(-5 + 2, -3 + 5) = (-3, 2)");
  eq("x = 1은 -6보다 7만큼 크고(1 − (-6) = 7), y는", "x = 1은 -6보다 7만큼 크고(1 − (-6) = 7), y는");
  eq("(계수 -9 ÷ (-3) = 3)", "(계수 -9 ÷ (-3) = 3)");
  eq("(√((-3)²)를 -3으로 쓰면 틀린다)", "(√((-3)²)를 -3으로 쓰면 틀린다)");
  eq("(예: 처음 두 항 1 + (-2))", "(예: 처음 두 항 1 + (-2))");
  eq("(4(x + 2) + 19 = 2x + 1)", "(4(x + 2) + 19 = 2x + 1)");
});

test("짝이 안 맞으면 손대지 않는다", () => {
  eq("(x − (-1)", "(x − (-1)");
  eq("x − (-1))", "x − (-1))");
});

test("renderHtml 이 마커 밖 평문에만 적용한다", () => {
  const h = renderHtml("(x − (-4))(x − (-3)) = 0 → [[frac(1, 2)]] × (a − (b − 1))");
  assert.ok(h.includes("{x − (-4)}{x − (-3)} = 0"), h);
  assert.ok(h.includes('class="mf"'), h);
  assert.ok(h.includes("{a − (b − 1)}"), h);
  assert.ok(!renderHtml("[[frac((a + (b − 1)), 2)]]").includes("{"), "마커 안은 그대로");
  assert.equal(renderHtml("(30 − x)/6 = 5").includes('class="mf"'), true, "한 겹 괄호 평문 분수는 여전히 상하로");
});

console.log(`\n${n - failed}/${n} 통과`);
if (failed) process.exit(1);
