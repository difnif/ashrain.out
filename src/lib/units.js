for (const [a, bs] of Object.entries(NEXT)) for (const b of bs) (PREV[b] ||= []).push(a);
export const nextUnits = (u) => NEXT[u] || [];
export const prevUnits = (u) => PREV[u] || [];

/** 한 방향으로 「콘텐츠가 있는」 단원들 — 3단계까지 가까운 것부터([{ u, d }], d = 몇 단계 건너) */
function nearest(u, step, has) {
  const seen = new Set([u]);
  let front = [u];
  const out = [];
  for (let d = 1; d <= 3; d++) {
    const nx = [];
    for (const x of front) for (const y of step(x)) if (!seen.has(y)) { seen.add(y); nx.push(y); }
    for (const y of nx) if (has(y)) out.push({ u: y, d });
    front = nx;
  }
  return out;
}

/**
 * 우물 추천 — item(.unit)의 같은 단원 · 앞 단원 · 다음 단원 콘텐츠를 고르게(최대 max)
 * pool: 고를 콘텐츠들(.key · .unit) · 돌려주는 것: [{ ...콘텐츠, rel: "같은 단원" | "앞 단원" | "다음 단원" }]
 */
export function relatedOf(item, pool, max = 6) {
  if (!item?.unit) return [];
  const by = new Map();
  for (const p of pool) if (p.unit && p.key !== item.key) { if (!by.has(p.unit)) by.set(p.unit, []); by.get(p.unit).push(p); }
  const has = (u) => by.has(u);
  const same = (by.get(item.unit) || []).map((p) => ({ ...p, rel: "같은 단원" }));
  const pick = (dir) => {
    const hits = nearest(item.unit, dir === "앞 단원" ? prevUnits : nextUnits, has);
    return hits.sort((a, b) => a.d - b.d || (dir === "앞 단원" ? termRank(b.u) - termRank(a.u) : termRank(a.u) - termRank(b.u)))
      .flatMap(({ u }) => by.get(u).map((p) => ({ ...p, rel: dir })));
  };
  const prev = pick("앞 단원"), next = pick("다음 단원");
  // 고르게: 앞 · 같은 · 다음을 하나씩 돌아가며
  const out = [], lists = [prev, same, next];
  for (let i = 0; out.length < max && lists.some((l) => i < l.length); i++) for (const l of lists) if (i < l.length && out.length < max) out.push(l[i]);
  return out;
}
