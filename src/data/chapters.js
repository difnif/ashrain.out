// concepts 표에는 대단원 칸이 없어서 여기서 정한다. 고등 학기는 아직 비워 두었다 → 학기 전체 하나로 묶인다.
// [단원 이름, 첫 번호, 끝 번호]
export const CHAPTERS = {
  "m1-1": [["소인수분해", 1, 8], ["정수와 유리수", 9, 18], ["문자와 식", 19, 28], ["좌표평면과 그래프", 29, 34]],
  "m1-2": [["기본 도형", 1, 6], ["평면도형의 성질", 7, 11], ["입체도형의 성질", 12, 16], ["자료의 정리와 해석", 17, 21]],
  "m2-1": [["수와 식", 1, 6], ["부등식", 7, 10], ["연립방정식", 11, 15], ["일차함수", 16, 23]],
  "m2-2": [["도형의 성질", 1, 4], ["도형의 닮음", 5, 9], ["피타고라스 정리", 10, 11], ["확률", 12, 14]],
  "m3-1": [["실수와 그 계산", 1, 6], ["다항식의 곱셈과 인수분해", 7, 13], ["이차방정식", 14, 21], ["이차함수", 22, 30]],
  "m3-2": [["삼각비", 1, 5], ["원의 성질", 6, 11], ["통계", 12, 14]],
};

/** 개념 id → { unit, name, idx } — 표에 없는 학기·번호는 '학기 전체'(idx 99) */
export function chapterOf(conceptId) {
  const m = /^([mh]\d-\d)-(\d+)$/.exec(String(conceptId || ""));
  if (!m) return { unit: null, name: "단원 미지정", idx: 99 };
  const unit = m[1], no = Number(m[2]);
  const list = CHAPTERS[unit] || [];
  const i = list.findIndex(([, a, b]) => no >= a && no <= b);
  return i < 0 ? { unit, name: "학기 전체", idx: 99 } : { unit, name: list[i][0], idx: i };
}
