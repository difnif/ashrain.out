def load_base():
    out = {}
    for f in os.listdir(SEEDS):
        if not f.endswith(".json") or "sangwa" in f:
            continue
        s = json.load(open(os.path.join(SEEDS, f), encoding="utf-8"))
        for t in s.get("templates", []):
            out[t["id"]] = (s, t)
    return out


def build_template(spec, base_seed, base_tpl, tid):
    t = {k: copy.deepcopy(v) for k, v in base_tpl.items() if k not in KEEP_OUT}
    t["id"] = tid
    t["title"] = spec["title"]
    t["qtype"] = "essay"
    t["pool_target"] = POOL
    t["points"] = spec["total"]
    t["rubric_total"] = spec["total"]
    t["time_limit"] = 300
    t["question"] = spec["q"]
    t["model_answer"] = spec["ma"]
    t["rubric"] = spec["rubric"]
    t["pitfalls"] = spec["pitfalls"]
    t["tags"] = list(dict.fromkeys(list(base_tpl.get("tags", [])) + ["서술형", "산과"]))
    for name, vals in (spec.get("params_in") or {}).items():
        for p in t["params"]:
            if p["name"] == name:
                p["values"] = {"in": vals}
    for key, rows in (spec.get("table_add") or {}).items():
        tbs = t["table"] if isinstance(t["table"], list) else [t["table"]]
        for tb in tbs:
            if tb["key"] == key:
                for rk, add in rows.items():
                    tb["rows"][rk].update(add)
    if spec.get("derive_add"):
        t["derive"] = {**t.get("derive", {}), **spec["derive_add"]}
    if spec.get("verify_add"):
        t["verify"] = list(t.get("verify", [])) + spec["verify_add"]
    t["variant_axis"] = {**base_tpl.get("variant_axis", {}), "원 틀": base_tpl["id"]}
    return t


def main():
    base = load_base()
    seeds = {}
    for spec in SPECS:
        bs, bt = base[spec["base"]]
        sid = spec["out"]
        if sid not in seeds:
            title, unit = SEED_META[sid]
            seeds[sid] = {"seed_id": sid, "category": "산과", "test_type": "sangwa", "title": title,
                          "unit_id": unit, "concept_ids": [spec["cid"]],
                          "schema_id": bs.get("schema_id"), "source_item_ids": [],
                          "note": "기존 생성 틀(concept_set)을 문정중 서답형 꼴로 다시 씀 — 파라미터·검증·해설은 원래 틀을 물려받음 (11-04)",
                          "geometry": bs.get("geometry", False), "templates": []}
        s = seeds[sid]
        assert s["concept_ids"] == [spec["cid"]], (sid, spec["cid"])
        tid = f"{sid}-t{len(s['templates']) + 1}"
        s["templates"].append(build_template(spec, bs, bt, tid))
    for sid, s in seeds.items():
        with open(os.path.join(SEEDS, sid + ".json"), "w", encoding="utf-8") as f:
            json.dump(s, f, ensure_ascii=False, indent=1)
            f.write("\n")
        print(f"{sid}: 틀 {len(s['templates'])}개 → seeds/{sid}.json")


if __name__ == "__main__":
    main()
